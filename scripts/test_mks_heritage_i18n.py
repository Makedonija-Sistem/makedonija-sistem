#!/usr/bin/env python3
"""May Heritage 58-section translation catalogue QA: no network, no deploy."""
from pathlib import Path
import hashlib
import json
import re
import sys
root=Path(__file__).resolve().parents[1]
read=lambda p:(root/p).read_text(encoding="utf-8")
fail=[]
def check(ok,what):
    if not ok:fail.append(what)
src=read("heritage/library.js")
match=re.search(r"window\.MKS_MAY_LIBRARY=Object\.freeze\((\{[\s\S]*\})\);",src)
check(bool(match),"original register readable")
catalogue=json.loads(match.group(1)) if match else {}
items=catalogue.get("sections",[])
check(len(items)==58 and len({r["id"] for r in items})==58,"original 58 IDs preserved")
check(len(catalogue.get("documents",[]))==26,"26 documents preserved")
check(catalogue.get("sourceCommit")=="a5f6f9f09e421309e267af384e945bbbdeb7b6d2","original May commit pointer retained")
check(catalogue.get("archiveBlob")=="408e8f69bbddbbdf7f5a1386f3aed0fed0812a5e","v17 source blob retained")
source_bytes=(root/"archive/makedonija-sistem-platform-v17-FINAL.html.disabled").read_bytes()
source_sha=hashlib.sha1(b"blob "+str(len(source_bytes)).encode()+b"\0"+source_bytes).hexdigest()
check(source_sha==catalogue.get("archiveBlob"),"source blob not modified")
archive=read("heritage/may-2026-v17-readonly.html")
check(len(re.findall(r'<section\b[^>]*\bid="[^"]+"',archive))==58,"read-only archive 58 sections")
check(not re.search(r"<script\b",archive,re.I) and "script-src 'none'" in archive,"archive still has no scripts")
html=read("heritage/index.html")
check("noindex,nofollow" in html and "connect-src 'none'" in html and "form-action 'none'" in html,"catalogue restrictive CSP")
for p in ["./library.js","./lang-data.js","./library-app.js"]:
    check('src="'+p+'"' in html,"local asset linked: "+p)
check("id=\"heritageLangNav\"" in html,"language chooser exists")
js=read("heritage/lang-data.js")
table=re.search(r'const rows=("(?:\\.|[^"\\])*")\.trim\(\)\.split\("\\n"\)',js)
check(bool(table),"title records parseable")
records=json.loads(table.group(1)).strip().split("\n") if table else []
parsed=[r.split("|") for r in records]
check(len(parsed)==58 and all(len(r)==5 for r in parsed),"58 x 4 title records")
check([r[0] for r in parsed]==[r["id"] for r in items],"translated ID order matches immutable source")
check(all(all(val.strip() and "<" not in val and ">" not in val for val in r) for r in parsed),"titles are nonempty plain text")
msgs=re.search(r"const messages=(\{.*\});\n  const locales=",js,re.S)
messages=json.loads(msgs.group(1)) if msgs else {}
check(set(messages)=={"mk","en","al","sr","de"},"exact five message dictionaries")
check(len({frozenset(x) for x in messages.values()})==1,"all five message key sets identical")
check(all(len(x)>=35 for x in messages.values()),"UI copy coverage")
for lang,strings in messages.items():
    check("titleCount" not in strings,"no misleading completeness label")
check("translatedBodies:0" in js,"honest full-text translation state")
app=read("heritage/library-app.js")
for banned in ["fetch(","XMLHttpRequest","sendBeacon","localStorage","sessionStorage",".innerHTML","eval(","new Function"]:
    check(banned not in js and banned not in app,"no dangerous or network script use: "+banned)
check('textContent' in app and "encodeURIComponent(lang)" in app,"safe text-only DOM and language query links")
check('may-2026-v17-readonly.html#' in app,"historical deep-link retained")
check('target="_blank"' not in app,"no autogenerated unsafe target")
check('replaceState' in app,"language in URL without local storage")
check((root/"assets/icons/icon.svg").exists(),"brand icon retained")
check('id="heritage-may"' in read("index.html"),"root heritage entry retained")
print(json.dumps({"status":"PASS" if not fail else "FAIL","translated_titles_per_target":len(records),
                  "ui_locales":sorted(messages),"source_sections":len(items),
                  "source_documents":len(catalogue.get("documents",[])),
                  "full_text_translations":"NOT COMPLETE","failures":fail},
                 ensure_ascii=False,indent=2))
sys.exit(bool(fail))
